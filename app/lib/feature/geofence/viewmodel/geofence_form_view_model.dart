class GeofenceFormState {
  final GeofenceDraft draft;
  final List<RecipientOption> recipients;
  final Map<GeofenceField, String> errors;
  final String? submitError;
  final bool saving;
  final bool saved;

  /// 사용자가 장소 이름을 직접 고쳤는지. 고쳤다면 지도 조작으로 덮어쓰지 않는다.
  final bool nameTouched;

  /// 알림 메시지가 아직 자동 생성 문구 그대로인지.
  final bool messageAutoGenerated;

  const GeofenceFormState({
    required this.draft,
    required this.recipients,
    this.errors = const {},
    this.submitError,
    this.saving = false,
    this.saved = false,
    required this.nameTouched,
    required this.messageAutoGenerated,
  });

  GeofenceFormState copyWith({
    GeofenceDraft? draft,
    Map<GeofenceField, String>? errors,
    String? submitError,
    bool clearSubmitError = false,
    bool? saving,
    bool? saved,
    bool? nameTouched,
    bool? messageAutoGenerated,
  }) => GeofenceFormState(
    draft: draft ?? this.draft,
    recipients: recipients,
    errors: errors ?? this.errors,
    submitError: clearSubmitError ? null : submitError ?? this.submitError,
    saving: saving ?? this.saving,
    saved: saved ?? this.saved,
    nameTouched: nameTouched ?? this.nameTouched,
    messageAutoGenerated: messageAutoGenerated ?? this.messageAutoGenerated,
  );
}

@riverpod
class GeofenceFormViewModel extends _$GeofenceFormViewModel {
  late GeofenceService _geofences;
  late MapSearchService _maps;

  @override
  Future<GeofenceFormState> build(
    GeofenceService geofenceService,
    GeofenceRecipientService recipientService,
    MapSearchService mapSearchService,
    int? id,
  ) async {
    _geofences = geofenceService;
    _maps = mapSearchService;
    final recipients = await recipientService.load();
    if (id == null) {
      final position = await _currentPosition();
      return GeofenceFormState(
        draft: GeofenceDraft.created(
          latitude: position.$1,
          longitude: position.$2,
        ),
        recipients: recipients,
        nameTouched: false,
        messageAutoGenerated: true,
      );
    }
    final draft = await geofenceService.loadDraft(id);
    if (draft == null) throw StateError('Geofence $id not found');
    // 수정할 때의 기존 값은 이미 사용자가 정한 것이므로 손댄 것으로 본다.
    return GeofenceFormState(
      draft: draft,
      recipients: recipients,
      nameTouched: true,
      messageAutoGenerated: false,
    );
  }

  /// 입력을 받았으면 true. 기기 연락처로 나가는 문자 본문이 한도를 넘기게 되는
  /// 입력은 받지 않고 false를 돌려주니, 화면은 입력칸을 이전 값으로 되돌린다.
  bool setName(String name) {
    final current = state.value;
    if (current == null) return true;
    var next = current.draft.copyWith(name: name);
    if (current.messageAutoGenerated) {
      next = next.copyWith(
        message: GeofenceDraft.defaultMessage(name, next.eventType),
      );
    }
    if (next.exceedsSmsLimitComparedTo(current.draft)) return false;
    state = AsyncData(
      current.copyWith(
        draft: next,
        nameTouched: true,
        errors: _without(current.errors, GeofenceField.name),
      ),
    );
    return true;
  }

  bool setMessage(String message) {
    final current = state.value;
    if (current == null) return true;
    final next = current.draft.copyWith(message: message);
    if (next.exceedsSmsLimitComparedTo(current.draft)) return false;
    state = AsyncData(
      current.copyWith(
        draft: next,
        messageAutoGenerated: false,
        errors: _without(current.errors, GeofenceField.message),
      ),
    );
    return true;
  }

  void setEventType(EventType eventType) {
    final current = state.value;
    if (current == null) return;
    var next = current.draft.copyWith(eventType: eventType);
    if (current.messageAutoGenerated) {
      next = next.copyWith(
        message: GeofenceDraft.defaultMessage(next.name, eventType),
      );
    }
    state = AsyncData(current.copyWith(draft: next));
  }

  void setActive(bool active) =>
      _updateDraft((draft) => draft.copyWith(active: active));

  void setRadius(GeofenceRadius radius) =>
      _updateDraft((draft) => draft.copyWith(radius: radius));

  void setRepeat(GeofenceRepeat repeat) {
    final current = state.value;
    if (current == null) return;
    state = AsyncData(
      current.copyWith(
        draft: current.draft.copyWith(repeat: repeat),
        errors: _without(current.errors, GeofenceField.repeatDays),
      ),
    );
  }

  void toggleRepeatDay(int weekday) {
    final current = state.value;
    if (current == null) return;
    final bitmask = current.draft.customDaysBitmask ^ (1 << (weekday - 1));
    state = AsyncData(
      current.copyWith(
        draft: current.draft.copyWith(customDaysBitmask: bitmask),
        errors: _without(current.errors, GeofenceField.repeatDays),
      ),
    );
  }

  void toggleRecipient(RecipientOption option) {
    final current = state.value;
    if (current == null) return;
    final currentlySelected = option.source == RecipientSource.device
        ? current.draft.deviceContactIds.contains(option.key)
        : current.draft.serverRecipientKeys.contains(option.key);
    Set<String> toggle(Set<String> keys) => keys.contains(option.key)
        ? ({...keys}..remove(option.key))
        : {...keys, option.key};
    final draft = option.source == RecipientSource.device
        ? current.draft.copyWith(
            deviceContactIds: toggle(current.draft.deviceContactIds),
          )
        : current.draft.copyWith(
            serverRecipientKeys: toggle(current.draft.serverRecipientKeys),
          );
    state = AsyncData(
      current.copyWith(
        draft: draft,
        errors: _without(current.errors, GeofenceField.recipients),
      ),
    );
    unawaited(
      _log('geofence_recipient_toggled', {
        'recipient_source': option.source.name,
        'selected': !currentlySelected ? 1 : 0,
      }),
    );
  }

  /// 지도를 눌러 위치를 고른다. 좌표는 바로 반영하고 주소는 서버에 물어 채운다.
  Future<void> selectLocation(double latitude, double longitude) async {
    _updateDraft(
      (draft) => draft.copyWith(latitude: latitude, longitude: longitude),
    );
    final result = await _maps.reverseGeocode(latitude, longitude);
    final current = state.value;
    // 응답이 오기 전에 다른 곳을 눌렀다면 지나간 응답이다.
    if (result == null ||
        current == null ||
        !ref.mounted ||
        current.draft.latitude != latitude ||
        current.draft.longitude != longitude) {
      return;
    }
    _applyPlace(
      current,
      address: result.fullAddress(latitude, longitude),
      proposedName: result.placeName ?? '',
    );
  }

  /// 검색 결과를 골라 위치, 주소, (비어 있으면) 이름을 한꺼번에 채운다.
  void selectPlace(PlaceSearchResultDto place) {
    final current = state.value;
    if (current == null) return;
    _applyPlace(
      current.copyWith(
        draft: current.draft.copyWith(
          latitude: place.latitude,
          longitude: place.longitude,
        ),
      ),
      address: place.address,
      proposedName: place.title,
    );
  }

  /// 저장에 성공하면 true.
  Future<bool> submit() async {
    final current = state.value;
    if (current == null || current.saving) return false;
    final errors = current.draft.validate();
    if (errors.isNotEmpty) {
      state = AsyncData(
        current.copyWith(errors: errors, clearSubmitError: true),
      );
      return false;
    }
    state = AsyncData(
      current.copyWith(errors: const {}, saving: true, clearSubmitError: true),
    );
    try {
      await _geofences.save(current.draft, current.recipients);
      await _logSaved(current.draft);
      if (ref.mounted) {
        state = AsyncData(
          (state.value ?? current).copyWith(saving: false, saved: true),
        );
      }
      return true;
    } catch (error, stack) {
      AppLogger.error('Geofence save failed', error, stack);
      if (ref.mounted) {
        state = AsyncData(
          (state.value ?? current).copyWith(
            saving: false,
            submitError: '알림 장소를 저장하지 못했어요',
          ),
        );
      }
      return false;
    }
  }

  /// 사용자가 이름을 직접 고쳤다면 지도 조작으로 덮어쓰지 않고, 비어 있을 때만 검색
  /// 결과나 주소의 이름으로 채운다.
  void _applyPlace(
    GeofenceFormState current, {
    required String address,
    required String proposedName,
  }) {
    final proposed = proposedName.trim();
    final name = current.nameTouched || proposed.isEmpty
        ? current.draft.name
        : proposed;
    var draft = current.draft.copyWith(address: address, name: name);
    if (current.messageAutoGenerated) {
      draft = draft.copyWith(
        message: GeofenceDraft.defaultMessage(name, draft.eventType),
      );
    }
    state = AsyncData(
      current.copyWith(
        draft: draft,
        errors: _without(current.errors, GeofenceField.address),
      ),
    );
  }

  void _updateDraft(GeofenceDraft Function(GeofenceDraft draft) change) {
    final current = state.value;
    if (current == null || !ref.mounted) return;
    state = AsyncData(current.copyWith(draft: change(current.draft)));
  }

  Future<(double, double)> _currentPosition() async {
    try {
      final position = await LocatePermissionService().getCurrentUserLocation();
      return (position.latitude, position.longitude);
    } catch (error, stack) {
      AppLogger.error('Current position unavailable', error, stack);
      return (defaultLatitude, defaultLongitude);
    }
  }

  Future<void> _logSaved(GeofenceDraft draft) async {
    await _log('geofence_saved', {
      'event_type': draft.eventType.name,
      'mode': draft.id == null ? 'create' : 'edit',
    });
  }

  Future<void> _log(String name, Map<String, Object> parameters) async {
    try {
      await ref
          .read(authAnalyticsReporterProvider)
          .logEvent(name, parameters: parameters);
    } catch (error, stack) {
      AppLogger.error('Geofence analytics failed', error, stack);
    }
  }

  static Map<GeofenceField, String> _without(
    Map<GeofenceField, String> errors,
    GeofenceField field,
  ) => {...errors}..remove(field);
}
